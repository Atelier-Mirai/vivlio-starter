# frozen_string_literal: true

# ================================================================
# Test: font_installed_test.rb
# ================================================================
# テスト対象:
#   FontManager の「取得済み」の判定と、取り直し
#
# 背景:
#   10/12 より前の雛形は stylesheets/fonts/google/Zen_Old_Mincho/ に TTF だけを配り、
#   @font-face は page-settings.css に書いていた。同梱の書体を Noto へ替えた後も
#   フォルダが残った本では、ファイルがあるので取得を飛ばし、google-fonts.css に
#   @font-face が書かれないまま、本文がフォールバックの HackGen（ゴシック）で組まれた。
#   警告は出なかった。
#
# 検証方法:
#   実際の HTTP は伴わない。download_google_font を差し替え、呼ばれたかと
#   google-fonts.css に書かれた中身を見る。
# ================================================================

require 'test_helper'
require 'tmpdir'
require 'fileutils'
require 'vivlio_starter/cli/font_manager'

module VivlioStarter
  module CLI
    class FontInstalledTest < Minitest::Test
      PLACEHOLDER = "/* No Google Fonts downloaded (generated by FontManager) */\n"

      FACE = <<~CSS
        @font-face {
          font-family: 'Zen Old Mincho';
          font-weight: 400;
          src: url("google/Zen_Old_Mincho/ZenOldMincho-Regular.ttf") format('truetype');
        }
      CSS

      def test_should_not_count_folder_without_font_face_as_installed
        in_project(bundle: PLACEHOLDER, files: ['Zen-Old-Mincho.ttf']) do
          refute FontManager.google_font_installed?('Zen Old Mincho')
        end
      end

      def test_should_count_folder_with_font_face_as_installed
        in_project(bundle: FontManager.build_block_entry('Zen Old Mincho', FACE), files: ['ZenOldMincho-Regular.ttf']) do
          assert FontManager.google_font_installed?('Zen Old Mincho')
        end
      end

      # 古い雛形のフォルダが残った本でも、次のビルドで取り直して @font-face を書く
      def test_should_download_again_when_only_folder_is_left
        in_project(bundle: PLACEHOLDER, files: ['Zen-Old-Mincho.ttf']) do
          requested = []
          download = lambda do |name|
            requested << name
            [[name, FontManager.build_block_entry(name, FACE)]]
          end

          FontManager.stub(:download_google_font, download) do
            FontManager.ensure_fonts_available(['Zen Old Mincho'])
          end

          assert_equal ['Zen Old Mincho'], requested
          assert_includes File.read(FontManager.google_bundle_path), "font-family: 'Zen Old Mincho'"
        end
      end

      private

      def in_project(bundle:, files:)
        Dir.mktmpdir do |dir|
          Dir.chdir(dir) do
            folder = File.join(FontManager.google_fonts_dir, 'Zen_Old_Mincho')
            FileUtils.mkdir_p(folder)
            files.each { FileUtils.touch(File.join(folder, it)) }
            File.write(FontManager.google_bundle_path, bundle)
            yield
          end
        end
      end
    end
  end
end
