# 責務:
#   交ぜ書き（熟語の一部の漢字だけをかなで書いた表記）の辞書を持つ。
#   検出と置換は ProseChecker が行い、ここは語のデータだけを預かる。
#
# 語の採否（仕様: lint-japanese-prose-rules-spec.md §3.2）:
#   1. 技術書・一般の文章に現れる
#   2. **他の語の一部として現れない綴り**（救えるものは GUARDED で前後を制約する）
#
#   **「かな書きのほうが主流だから」は載せない理由にならない。** 常用漢字表が
#   2000 字余りに収まらないため交ぜ書きが主流になった語（改ざん・せん断・宝くじ）も、
#   漢字表記そのものは正しく、きちんと書けることに価値がある。読み手を選ぶ漢字を
#   避けたい著者は config/textlint_allowlist.yml に語を書けば黙る（語単位）。
#   **辞書は「漢字表記があるものは載せる」、選ぶのは著者**という切り分けにする。
#
#   この基準は 2 度動いた。当初は「世間の標準表記になっている語は載せない」として
#   改ざん・宝くじを外し、次に「規格が表記を定める語（JIS のせん断）だけ外す」へ狭め、
#   2026-08-18 に除外そのものをやめた。除外の線引きは書き手の方針であって、
#   辞書の側で決めるものではなかった。
#
# 2 で落とした語（**理由ごと消さないこと**。消すと同じ誤検出を踏み直す）:
#   う回（迂回）    「使う回数」「行なう回数」に当たる。直前がひらがな・漢字だと
#                   動詞の終止形と区別できず、制約で救えない → MECAB_ONLY へ
#   い縮（萎縮）    「短い縮小」に当たる
#   そ上（俎上）    「およそ上位」に当たる。加えて「遡上」とも読めて行き先が定まらない
#   り患（罹患）    「〜であり患者は」に当たる → MECAB_ONLY へ
#   ほう起（蜂起）  「そのほう起きる」に当たる
#   こう頭（喉頭）  「行こう頭から」に当たる
#   でん粉（澱粉）  「うどん粉」に当たる
#   語い（語彙）    「日本語いろは」に当たる。後続がひらがなの用法（「語いが豊富」）
#                   まで落とさないと救えず、それでは検出のほうが残らない → MECAB_ONLY へ
#   ろ過（濾過）    「見ろ過去の」に当たる。後続も「過」なので後ろで切れない
#   だ液（唾液）    「〜だ液体では」に当たる
#   き釈（希釈）    「大き釈明」に当たる
#   せん削（穿削）  「動きません削除」に当たる
#   ち密（緻密）    「持ち密度」に当たる
#   語ろ（語呂）    「歴史を語ろうとする」に当たる
#   御す（御簾）    「部下を御する」に当たる。「御す（ぎょす）」自体が正しい語
#   交し（交趾）    「言葉を交して」「契約を交した」に当たる
#   りん子（綸子）  「りん子さん」（人名）に当たる。絹織物の名で技術書には出ない
#
#   直上の 4 語は同じ型で、**交ぜ書き表記がそのまま別語として読める**（語ろ＝かたろ、
#   御す＝ぎょす、交し＝かわし、りん子＝りんこ）。同音異義語ではなく同表記異読なので、
#   形態素解析でも落とせない。**語を足す前に、その綴りが別の読みで成立しないか確かめること。**
#
#   **「かく乱」をここへ戻さないこと。** 一度「書く乱れた字に当たる」として落としたが、
#   これは誤りだった——「書く乱れ」の「書」は漢字なので「かく乱」の並びにならない。
#   実際に当たるのは「とにかく乱暴」「せっかく乱れて」のひらがな副詞で、そちらは
#   GUARDED の制約で外せる。**綴りの危険は、頭の中でなく実際の文字列で確かめる。**
#   同じ理由で「き損」「き裂」も後続の制約で救えた（2026-08-18 に再検討して追加）。
#   「は種（播種）」「合し（合祀）」も同様——後続を `別類目子` で外し、直前の漢字を
#   外すだけで、「後書き（99）は種別が」「結合し直した」が消えた（2026-08-19）。
#
#   **救えるかどうかは 2 段ある。** 前後の制約だけで消えるものは GUARDED に置き、
#   形態素の境界を見ないと消えないものは MECAB_ONLY に置く。後者は MeCab が無い環境で
#   黙るぶん取りこぼすが、誤検出を出すよりよい。
#
# 語形が交ぜ書きでないため載せない語:
#   **全体がかな書きの語は交ぜ書きではない。** 「らち」「はたん」「そご」「かんがい」
#   「へんこう」のような形は、漢字とかなが混ざっていないので本ルールの対象外である。
#   加えて同音語との衝突が避けられない——「らち → 拉致」は「らちが明かない（埒）」を、
#   「へんこう → 偏光」は「変更」を、「かんがい → 灌漑」は「感慨」を壊す。
#   かな書きを漢字へ起こす仕事は形態素解析（文脈判断）の領分であって、
#   辞書の単純置換では扱えない。
#
# 出典データの誤りとして採らなかったもの（2026-08-18 に受け取った分野別の変換表より）:
#   そう打 → 操舵 / 摩かん → 摩天 / ち電 → 沈殿 / ち遅 → 遅延 / そう相 → 相殺 /
#   せん妄 → 閃妄（正しくは譫妄）/ えしゃ → 壊死 / なりすまし → 冒頭・仮装
#   いずれも読みと熟語が対応しない。**変換先が誤った辞書は --fix が原稿を壊す**ので、
#   語を足すときは必ず読みと熟語の対応を確かめること。
# ================================================================

